from typing import Dict, List, Optional
import numpy as np
import pandas as pd

from sklearn.preprocessing import StandardScaler
from ucimlrepo import fetch_ucirepo


# ==========================================
# 1. DEFAULT SETTINGS
# ==========================================

DATE_COL = "date"
DEFAULT_TARGET_COL = "Usage_kWh"

NUMERIC_FEATURES = [
    "Usage_kWh",
    "Lagging_Current_Reactive.Power_kVarh",
    "Leading_Current_Reactive_Power_kVarh",
    "CO2(tCO2)",
    "Lagging_Current_Power_Factor",
    "Leading_Current_Power_Factor",
    "NSM",
]

# 7 original numerical features + 4 engineered/encoded features
DEFAULT_FEATURE_COLS = NUMERIC_FEATURES + [
    "WeekStatus_code",
    "Day_of_week_code",
    "Load_Type_code",
    "Hour",
]

INPUT_LEN = 96
HORIZON_LEN = 96


# ==========================================
# 2. LOAD DATA
# ==========================================

def load_data(uci_id: int = 851) -> pd.DataFrame:

    # Keep the original UCI loading method
    steel_industry_energy_consumption = fetch_ucirepo(id=uci_id)

    X = steel_industry_energy_consumption.data.features
    y = steel_industry_energy_consumption.data.targets

    df = pd.concat([X, y], axis=1)

    # Remove duplicated column names if any
    df = df.loc[:, ~df.columns.duplicated()]

    return df


# ==========================================
# 3. DATA CLEANING
# ==========================================

def clean_data(
    df: pd.DataFrame,
    date_col: str = DATE_COL
) -> pd.DataFrame:

    df = df.copy()

    # Convert date column to datetime
    df[date_col] = pd.to_datetime(
        df[date_col], errors="coerce"
    )

    # Remove rows with invalid dates
    df = df.dropna(subset=[date_col])

    # Sort data chronologically
    df = df.sort_values(date_col).reset_index(drop=True)

    # Remove duplicate rows
    df = df.drop_duplicates().reset_index(drop=True)

    # Identify numerical and categorical columns
    numeric_cols = df.select_dtypes(
        include=np.number
    ).columns

    categorical_cols = df.select_dtypes(
        include=["object", "category"]
    ).columns

    # Fill missing values using previous observations
    df[numeric_cols] = df[numeric_cols].ffill()
    df[categorical_cols] = df[categorical_cols].ffill()

    return df



# ==========================================
# 4. FEATURE ENGINEERING
# ==========================================

def prepare_features(
    df: pd.DataFrame,
    date_col: str = DATE_COL
) -> pd.DataFrame:

    df = df.copy()

    # Extract hour from date
    df["Hour"] = df[date_col].dt.hour

    # Encode categorical columns
    categorical_features = [
        "WeekStatus",
        "Day_of_week",
        "Load_Type"
    ]

    for col in categorical_features:

        if col not in df.columns:
            raise ValueError(
                f"Required column '{col}' is missing."
            )

        categories = sorted(
            df[col].dropna().astype(str).unique()
        )

        category_mapping = {
            category: index
            for index, category in enumerate(categories)
        }

        df[f"{col}_code"] = (
            df[col].astype(str).map(category_mapping)
        )

    # Check all required features
    missing_cols = [
        col for col in DEFAULT_FEATURE_COLS
        if col not in df.columns
    ]

    if missing_cols:
        raise ValueError(
            f"Missing feature columns: {missing_cols}"
        )

    return df


# ==========================================
# 5. CREATE SEQUENCES
# ==========================================

def create_sequences(
    X: np.ndarray,
    y: np.ndarray,
    input_len: int = INPUT_LEN,
    horizon_len: int = HORIZON_LEN
):

    X_sequences = []
    y_sequences = []

    total_samples = len(X) - input_len - horizon_len + 1

    for i in range(total_samples):

        # Previous 96 readings
        X_sequences.append(
            X[i : i + input_len]
        )

        # Next 96 target readings
        y_sequences.append(
            y[i + input_len : i + input_len + horizon_len]
        )

    return (
        np.asarray(X_sequences, dtype=np.float32),
        np.asarray(y_sequences, dtype=np.float32)
    )


# ==========================================
# 6. MAIN DATA PREPARATION FUNCTION
# ==========================================

def prepare_datasets(
    df: Optional[pd.DataFrame] = None,
    uci_id: int = 851,
    date_col: str = DATE_COL,
    feature_cols: Optional[List[str]] = None,
    target_col: str = DEFAULT_TARGET_COL,
    train_ratio: float = 0.70,
    val_ratio: float = 0.15,
    input_len: int = INPUT_LEN,
    horizon_len: int = HORIZON_LEN
) -> Dict:

    # Load data if no dataframe is supplied
    if df is None:
        df = load_data(uci_id)

    # Validate split ratios
    test_ratio = 1 - train_ratio - val_ratio

    if train_ratio <= 0 or val_ratio <= 0 or test_ratio <= 0:
        raise ValueError("Invalid train/validation/test ratios.")

    # Clean data
    df = clean_data(df, date_col)

    # Create engineered features
    df = prepare_features(df, date_col)

    if feature_cols is None:
        feature_cols = DEFAULT_FEATURE_COLS.copy()

    # Check target
    if target_col not in df.columns:
        raise ValueError(f"Target column '{target_col}' is missing.")

    # Remove rows with missing required values
    df = df.dropna(
        subset=feature_cols + [target_col]
    ).reset_index(drop=True)

    # Extract arrays
    X = df[feature_cols].to_numpy(dtype=np.float64)
    y = df[[target_col]].to_numpy(dtype=np.float64)

    # ======================================
    # Chronological Train / Val / Test Split
    # ======================================

    n = len(df)

    train_end = int(n * train_ratio)
    val_end = int(n * (train_ratio + val_ratio))

    X_train = X[:train_end]
    X_val = X[train_end:val_end]
    X_test = X[val_end:]

    y_train = y[:train_end]
    y_val = y[train_end:val_end]
    y_test = y[val_end:]

    # ======================================
    # Scaling - Fit on TRAIN only
    # ======================================

    scaler_X = StandardScaler()
    scaler_y = StandardScaler()

    X_train_scaled = scaler_X.fit_transform(X_train)
    X_val_scaled = scaler_X.transform(X_val)
    X_test_scaled = scaler_X.transform(X_test)

    y_train_scaled = scaler_y.fit_transform(y_train)
    y_val_scaled = scaler_y.transform(y_val)
    y_test_scaled = scaler_y.transform(y_test)

    # ======================================
    # Create 96 -> 96 Sequences
    # ======================================

    X_train_seq, Y_train_seq = create_sequences(
        X_train_scaled, y_train_scaled,
        input_len, horizon_len
    )

    X_val_seq, Y_val_seq = create_sequences(
        X_val_scaled, y_val_scaled,
        input_len, horizon_len
    )

    X_test_seq, Y_test_seq = create_sequences(
        X_test_scaled, y_test_scaled,
        input_len, horizon_len
    )

    # ======================================
    # Report
    # ======================================

    report = {
        "total_rows": n,
        "train_rows": len(X_train),
        "validation_rows": len(X_val),
        "test_rows": len(X_test),

        "train_percentage": len(X_train) / n * 100,
        "validation_percentage": len(X_val) / n * 100,
        "test_percentage": len(X_test) / n * 100,

        "number_of_features": len(feature_cols),
        "feature_columns": feature_cols,

        "input_length": input_len,
        "forecast_horizon": horizon_len,

        "X_train_shape": X_train_seq.shape,
        "Y_train_shape": Y_train_seq.shape,

        "X_val_shape": X_val_seq.shape,
        "Y_val_shape": Y_val_seq.shape,

        "X_test_shape": X_test_seq.shape,
        "Y_test_shape": Y_test_seq.shape,
    }

    return {
        "X_train": X_train_seq,
        "Y_train": Y_train_seq,

        "X_val": X_val_seq,
        "Y_val": Y_val_seq,

        "X_test": X_test_seq,
        "Y_test": Y_test_seq,

        "scaler_X": scaler_X,
        "scaler_y": scaler_y,

        "report": report,
        "feature_cols": feature_cols,
        "cleaned_df": df,
        "X_train_raw": X_train,
        "y_train_raw": y_train,
    }